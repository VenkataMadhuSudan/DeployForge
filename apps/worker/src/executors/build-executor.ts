import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import Docker from 'dockerode';
import { LogLevel, BuildStage } from '@deployforge/shared-types';
import { SecretRedactor, sanitizeLogContent } from '@deployforge/logging';
import { loadConfig } from '@deployforge/configuration';

export interface BuildExecutionInput {
  workspacePath: string;
  installCommand?: string | null;
  buildCommand?: string | null;
  outputDirectory: string;
  envVars: Record<string, string>;
  redactor: SecretRedactor;
  onLog: (level: LogLevel, stage: BuildStage, message: string) => Promise<void>;
}

export interface BuildExecutionResult {
  success: boolean;
  artifactPath: string;
  exitCode: number;
  durationMs: number;
  errorMessage?: string;
}

export interface BuildExecutor {
  readonly executorType: string;
  executeBuild(input: BuildExecutionInput): Promise<BuildExecutionResult>;
}

export class ProcessBuildExecutor implements BuildExecutor {
  readonly executorType = 'PROCESS_SANDBOX';

  async executeBuild(input: BuildExecutionInput): Promise<BuildExecutionResult> {
    const startTime = Date.now();
    const config = loadConfig();
    const timeoutMs = config.BUILD_TIMEOUT_SECONDS * 1000;

    await input.onLog(LogLevel.INFO, BuildStage.PREPARE, 'Initializing sandboxed build workspace...');

    // 1. Install Dependencies Stage
    if (input.installCommand && input.installCommand.trim() !== '') {
      await input.onLog(LogLevel.INFO, BuildStage.INSTALL, `Executing install command: ${input.installCommand}`);
      const installRes = await this.runCommand(
        input.installCommand,
        input.workspacePath,
        input.envVars,
        BuildStage.INSTALL,
        input,
        timeoutMs
      );
      if (installRes.exitCode !== 0) {
        return {
          success: false,
          artifactPath: '',
          exitCode: installRes.exitCode,
          durationMs: Date.now() - startTime,
          errorMessage: `Dependency installation failed with code ${installRes.exitCode}`,
        };
      }
    }

    // 2. Build Stage
    if (input.buildCommand && input.buildCommand.trim() !== '') {
      await input.onLog(LogLevel.INFO, BuildStage.BUILD, `Executing build command: ${input.buildCommand}`);
      const buildRes = await this.runCommand(
        input.buildCommand,
        input.workspacePath,
        input.envVars,
        BuildStage.BUILD,
        input,
        timeoutMs
      );
      if (buildRes.exitCode !== 0) {
        return {
          success: false,
          artifactPath: '',
          exitCode: buildRes.exitCode,
          durationMs: Date.now() - startTime,
          errorMessage: `Build script failed with code ${buildRes.exitCode}`,
        };
      }
    }

    // 3. Artifact Validation
    const artifactPath = path.resolve(input.workspacePath, input.outputDirectory);
    if (!fs.existsSync(artifactPath)) {
      await input.onLog(
        LogLevel.ERROR,
        BuildStage.BUILD,
        `Expected build output directory not found: ${input.outputDirectory}`
      );
      return {
        success: false,
        artifactPath: '',
        exitCode: 1,
        durationMs: Date.now() - startTime,
        errorMessage: `Artifact output directory '${input.outputDirectory}' was not generated by the build`,
      };
    }

    await input.onLog(
      LogLevel.INFO,
      BuildStage.BUILD,
      `Build completed successfully. Validated artifact directory at ${input.outputDirectory}`
    );

    return {
      success: true,
      artifactPath,
      exitCode: 0,
      durationMs: Date.now() - startTime,
    };
  }

  private runCommand(
    commandStr: string,
    cwd: string,
    env: Record<string, string>,
    stage: BuildStage,
    input: BuildExecutionInput,
    timeoutMs: number
  ): Promise<{ exitCode: number }> {
    return new Promise((resolve) => {
      const isWindows = process.platform === 'win32';
      const shell = isWindows ? 'cmd.exe' : '/bin/sh';
      const shellArgs = isWindows ? ['/d', '/s', '/c', commandStr] : ['-c', commandStr];

      const child = spawn(shell, shellArgs, {
        cwd,
        env: {
          ...process.env,
          ...env,
          CI: 'true',
          NODE_ENV: 'production',
        },
        windowsHide: true,
      });

      let timedOut = false;
      const timer = setTimeout(() => {
        timedOut = true;
        child.kill('SIGKILL');
        input.onLog(LogLevel.ERROR, stage, `Execution exceeded timeout limit of ${timeoutMs / 1000} seconds`);
      }, timeoutMs);

      child.stdout.on('data', async (chunk: Buffer) => {
        const text = chunk.toString('utf8');
        const lines = text.split(/\r?\n/).filter((l) => l.trim().length > 0);
        for (const line of lines) {
          const redacted = input.redactor.redact(line);
          await input.onLog(LogLevel.INFO, stage, sanitizeLogContent(redacted));
        }
      });

      child.stderr.on('data', async (chunk: Buffer) => {
        const text = chunk.toString('utf8');
        const lines = text.split(/\r?\n/).filter((l) => l.trim().length > 0);
        for (const line of lines) {
          const redacted = input.redactor.redact(line);
          await input.onLog(LogLevel.WARN, stage, sanitizeLogContent(redacted));
        }
      });

      child.on('close', (code) => {
        clearTimeout(timer);
        resolve({ exitCode: timedOut ? 124 : (code ?? 1) });
      });

      child.on('error', async (err) => {
        clearTimeout(timer);
        await input.onLog(LogLevel.ERROR, stage, `Process execution error: ${err.message}`);
        resolve({ exitCode: 1 });
      });
    });
  }
}

export class DockerBuildExecutor implements BuildExecutor {
  readonly executorType = 'DOCKER_CONTAINER';
  private docker: Docker;

  constructor() {
    this.docker = new Docker();
  }

  async executeBuild(input: BuildExecutionInput): Promise<BuildExecutionResult> {
    const config = loadConfig();
    const startTime = Date.now();
    await input.onLog(LogLevel.INFO, BuildStage.PREPARE, 'Spawning isolated Docker build container (non-root UID 10001)...');

    try {
      // Create container with explicit resource limits and non-root user
      const container: any = await this.docker.createContainer({
        Image: 'node:20-alpine',
        Cmd: ['/bin/sh', '-c', `${input.installCommand ? `${input.installCommand} && ` : ''}${input.buildCommand || 'echo done'}`],
        WorkingDir: '/workspace',
        User: '10001:10001',
        HostConfig: {
          Memory: config.BUILD_MEMORY_LIMIT_MB * 1024 * 1024,
          NanoCpus: Math.floor(config.BUILD_CPU_LIMIT * 1e9),
          PidsLimit: config.BUILD_MAX_PROCESSES,
          Privileged: false,
          CapDrop: ['ALL'],
          Binds: [`${path.resolve(input.workspacePath)}:/workspace:rw`],
          AutoRemove: false,
        },
        Env: Object.entries(input.envVars).map(([k, v]) => `${k}=${v}`),
      });

      await container.start();

      const stream = await container.logs({
        follow: true,
        stdout: true,
        stderr: true,
      });

      stream.on('data', async (chunk: Buffer) => {
        const text = chunk.toString('utf8');
        const lines = text.split(/\r?\n/).filter((l) => l.trim().length > 0);
        for (const line of lines) {
          const clean = input.redactor.redact(line);
          await input.onLog(LogLevel.INFO, BuildStage.BUILD, sanitizeLogContent(clean));
        }
      });

      const waitResult = await container.wait();
      await container.remove({ force: true });

      const artifactPath = path.resolve(input.workspacePath, input.outputDirectory);
      const success = waitResult.StatusCode === 0 && fs.existsSync(artifactPath);

      return {
        success,
        artifactPath,
        exitCode: waitResult.StatusCode,
        durationMs: Date.now() - startTime,
        errorMessage: success ? undefined : `Build container exited with code ${waitResult.StatusCode}`,
      };
    } catch (err: any) {
      await input.onLog(LogLevel.ERROR, BuildStage.SYSTEM, `Docker executor failure: ${err.message}`);
      return {
        success: false,
        artifactPath: '',
        exitCode: 1,
        durationMs: Date.now() - startTime,
        errorMessage: err.message,
      };
    }
  }
}

export async function createBuildExecutor(): Promise<BuildExecutor> {
  // Try Docker connection; if Docker daemon is not active on current host, use sandboxed process executor
  try {
    const docker = new Docker();
    await docker.ping();
    return new DockerBuildExecutor();
  } catch {
    return new ProcessBuildExecutor();
  }
}
