export interface DeploymentDiagnostic {
  stage: string;
  category:
    | 'MISSING_DEPENDENCY'
    | 'SSR_PROVIDER_INCOMPATIBILITY'
    | 'MISSING_ENVIRONMENT_VARIABLE'
    | 'MISSING_BUILD_OUTPUT'
    | 'COMPILATION_ERROR'
    | 'RUNTIME_STARTUP_FAILURE'
    | 'HEALTH_CHECK_FAILURE'
    | 'INSTALLATION_SCRIPT_RESTRICTION'
    | 'DATABASE_CONFIGURATION_ERROR'
    | 'GENERAL_EXECUTION_FAILURE';
  summary: string;
  likelyCause: string;
  suggestedAction: string;
}

export function diagnoseDeploymentError(
  stage: string,
  rawError: string,
  context?: {
    exitCode?: number;
    outputDirectory?: string;
    deploymentUrl?: string;
  }
): DeploymentDiagnostic {
  const err = (rawError || '').trim();

  // 1. Missing module / build dependency
  const moduleMatch = err.match(/Cannot find module ['"]([^'"]+)['"]/i) || err.match(/Module not found: Can't resolve ['"]([^'"]+)['"]/i);
  if (moduleMatch) {
    const moduleName = moduleMatch[1];
    return {
      stage,
      category: 'MISSING_DEPENDENCY',
      summary: `Unresolved dependency: '${moduleName}'`,
      likelyCause: `The required module '${moduleName}' is missing from the installed node_modules. It may be omitted from package.json, or placed in devDependencies and pruned during installation.`,
      suggestedAction: `Ensure '${moduleName}' is declared in package.json under dependencies or devDependencies, and that the installation stage includes development dependencies during build execution.`,
    };
  }

  // 2. Unsupported SSR on static provider
  if (err.includes("output: 'export'") || err.includes('Server-Side Rendering (SSR)')) {
    return {
      stage,
      category: 'SSR_PROVIDER_INCOMPATIBILITY',
      summary: 'Next.js Server-Side Rendering (SSR) detected on static hosting provider',
      likelyCause: 'The project contains server-side components, dynamic routes, or API handlers requiring a Node.js application server, but the selected provider only hosts static files.',
      suggestedAction: "Select the 'Local Testing' provider with isolated Node.js SSR runtime support, or configure next.config.js with output: 'export' if purely static hosting is desired.",
    };
  }

  // 3. EALLOWSCRIPTS or install-scripts restrictions
  if (err.includes('EALLOWSCRIPTS') || err.includes('--allow-scripts')) {
    return {
      stage,
      category: 'INSTALLATION_SCRIPT_RESTRICTION',
      summary: 'Package install script restriction',
      likelyCause: 'The package manager blocked lifecycle install scripts due to global/user allow-scripts security configuration in ~/.npmrc.',
      suggestedAction: 'Isolate user configuration using a project-specific .npmrc or configure allowScripts in package.json.',
    };
  }

  // 4. Missing Database URL / Prisma configuration
  if (err.includes('DATABASE_URL') || err.includes('PrismaClientInitializationError')) {
    return {
      stage,
      category: 'DATABASE_CONFIGURATION_ERROR',
      summary: 'Missing or invalid database connection string',
      likelyCause: 'Prisma Client or application runtime could not find the DATABASE_URL environment variable during build-time page evaluation or query execution.',
      suggestedAction: 'Add a valid DATABASE_URL in the project Environment Variables dashboard under Settings.',
    };
  }

  // 5. Missing environment variable
  const envMatch = err.match(/Environment variable not found:\s*([A-Z0-9_]+)/i) || err.match(/process\.env\.([A-Z0-9_]+)\s+is\s+undefined/i);
  if (envMatch) {
    const varName = envMatch[1];
    return {
      stage,
      category: 'MISSING_ENVIRONMENT_VARIABLE',
      summary: `Missing required environment variable: '${varName}'`,
      likelyCause: `The application attempted to read '${varName}' at build or startup time, but no matching project environment variable was configured.`,
      suggestedAction: `Navigate to Project Settings > Environment Variables in the DeployForge dashboard and provide '${varName}'.`,
    };
  }

  // 6. Missing build output directory
  if (err.includes('Expected build output directory not found') || err.includes('not generated by the build')) {
    return {
      stage,
      category: 'MISSING_BUILD_OUTPUT',
      summary: `Build output directory '${context?.outputDirectory || 'configured'}' was not created`,
      likelyCause: `The build command completed, but the expected artifacts directory was not created. The framework may output to a different directory (e.g. '.next', 'dist', or 'out').`,
      suggestedAction: `Verify your project's build output path in project settings, or let DeployForge auto-detect the framework output directory.`,
    };
  }

  // 7. Health check failure
  if (err.includes('health check') || err.includes('Health check')) {
    return {
      stage,
      category: 'HEALTH_CHECK_FAILURE',
      summary: 'Post-deployment health check failed',
      likelyCause: `The published URL (${context?.deploymentUrl || 'local endpoint'}) did not return a successful HTTP response within the timeout period.`,
      suggestedAction: 'Inspect runtime application logs to ensure the server starts cleanly, binds to the assigned port, and returns HTTP 200 on the root route.',
    };
  }

  // 8. Runtime startup failure
  if (stage === 'DEPLOY' && (err.includes('Runtime process') || err.includes('failed to become healthy'))) {
    return {
      stage,
      category: 'RUNTIME_STARTUP_FAILURE',
      summary: 'Application runtime failed to start',
      likelyCause: 'The application start command exited unexpectedly or timed out before binding to the assigned internal port.',
      suggestedAction: 'Check that package.json has a valid start script (e.g. "next start") and that all required production environment variables are configured.',
    };
  }

  // 9. Compilation error
  if (stage === 'BUILD') {
    return {
      stage,
      category: 'COMPILATION_ERROR',
      summary: 'Build compilation script failed',
      likelyCause: `The build script exited with code ${context?.exitCode ?? 1}. Error: ${err.slice(0, 300)}`,
      suggestedAction: 'Review the detailed build stage logs above to fix syntax, type, or bundler configuration errors in the repository.',
    };
  }

  // Default general fallback
  return {
    stage,
    category: 'GENERAL_EXECUTION_FAILURE',
    summary: `Execution failed at stage: ${stage}`,
    likelyCause: err.slice(0, 300),
    suggestedAction: 'Review the stage execution logs above for detailed command output and diagnostics.',
  };
}
